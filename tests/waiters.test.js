const test = require('node:test');
const assert = require('node:assert/strict');
const { randomBytes, scryptSync } = require('node:crypto');
const fs = require('node:fs'), os = require('node:os'), path = require('node:path');
const { openDatabase } = require('../src/desktop/database');
const { bootstrap, registerSession } = require('../src/desktop/session');
const { registerTables, seedTables } = require('../src/desktop/tables');
test('selection enforces active identities, optional PIN and selected grants at the service boundary', t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'arra-waiters-'));
  const db = openDatabase(dir); t.after(() => { db.close(); fs.rmSync(dir, { recursive: true, force: true }); });
  bootstrap(db, 'restaurant', 'example password'); seedTables(db);
  const pin = String(randomBytes(2).readUInt16BE() % 10000).padStart(4, '0');
  const wrongPin = String((Number(pin) + 1) % 10000).padStart(4, '0');
  const salt = randomBytes(16), hash = scryptSync(pin, salt, 32, { N: 32768, r: 8, p: 1, maxmem: 64 * 1024 * 1024 });
  db.prepare('INSERT INTO local_users (username, salt, password_hash, pin_salt, pin_hash) VALUES (?, ?, ?, ?, ?)').run('sample waiter', randomBytes(16), randomBytes(32), salt, hash);
  db.prepare("INSERT INTO local_users (username, salt, password_hash, active) VALUES ('inactive', x'00', x'00', 0)").run();
  const handlers = {}, trusted = {}; const ipc = { handle(c, f) { handlers[c] = f; } };
  const session = registerSession(ipc, e => e === trusted, db); registerTables(ipc, e => e === trusted, db, session);
  const call = (c, data, event = trusted) => handlers['arra:' + c](event, data);
  assert.equal(call('waiters', {}).ok, false); assert.equal(call('select-waiter', { id: 1, pin: '' }).ok, false);
  assert.equal(call('sign-in', { username: 'restaurant', password: 'example password' }).ok, true);
  assert.deepEqual(call('waiters', {}).data.map(w => [w.name, w.hasPin]), [['restaurant', false], ['sample waiter', true]]);
  assert.equal(call('tables', {}).ok, false);
  assert.equal(call('select-waiter', { id: 1, pin: '' }, {}).ok, false);
  assert.equal(call('select-waiter', { id: 3, pin: '' }).ok, false);
  assert.equal(call('select-waiter', { id: 1, pin: '' }).ok, true); assert.equal(call('tables', {}).ok, true);
  assert.equal(call('select-waiter', { id: 2, pin: wrongPin }).ok, false); assert.equal(session.currentUserId(), 1);
  assert.equal(call('select-waiter', { id: 2, pin }).ok, true); assert.equal(session.currentUserId(), 2); assert.equal(call('tables', {}).ok, false);
  db.prepare("INSERT INTO user_permissions VALUES (2, 'tables.view')").run(); assert.equal(call('tables', {}).ok, true);
  db.prepare('UPDATE local_users SET active = 0 WHERE id = 2').run(); assert.equal(call('tables', {}).ok, false);
  assert.equal(call('select-waiter', { id: 2, pin }).ok, false);
  assert.equal(call('clear-waiter', {}).ok, true); assert.equal(session.currentUserId(), null);
  assert.equal(call('sign-out', {}).ok, true); assert.equal(call('waiters', {}).ok, false);
});
