const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const vm = require('node:vm');
const { openDatabase } = require('../src/desktop/database');
const { authorizedDatabase } = require('./support/authorized-database');
const { registerMenu, seedMenu } = require('../src/desktop/menu');
test('waiter menu keeps active subcategories under their parent and direct products reachable', async t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'arra-hierarchy-'));
  const db = authorizedDatabase(openDatabase(dir)); t.after(() => { db.close(); fs.rmSync(dir, {recursive:true, force:true}); }); seedMenu(db);
  db.prepare('INSERT INTO menu_categories (id,name,active,parent_id,sort_order) VALUES (?,?,?,?,?)').run('grill','Grill',1,'food',0);
  db.prepare('INSERT INTO menu_categories (id,name,active,parent_id,sort_order) VALUES (?,?,?,?,?)').run('hidden','Hidden',0,'food',1);
  db.prepare('INSERT INTO menu_categories (id,name,active,parent_id,sort_order) VALUES (?,?,?,?,?)').run('hidden-child','Hidden child',1,'desserts',0);
  db.prepare('UPDATE menu_categories SET active=0 WHERE id=?').run('desserts');
  db.prepare('INSERT INTO menu_products (id,category_id,name,price,active,sort_order) VALUES (?,?,?,?,?,?)').run('steak','grill','Steak',200,1,0);
  db.prepare('INSERT INTO menu_products (id,category_id,name,price,active,sort_order) VALUES (?,?,?,?,?,?)').run('hidden-product','hidden','Hidden dish',100,1,0);
  let handler; const trusted = {}; registerMenu({handle(_channel, fn) { handler=fn; }}, event => event === trusted, db, {currentUserId:()=>1,authenticatedUserId:()=>1});
  let api; vm.runInNewContext(fs.readFileSync(require.resolve('../src/desktop/preload.js'),'utf8'), { require: () => ({contextBridge:{exposeInMainWorld(_name, value){api=value;}},ipcRenderer:{invoke:async (_channel, request)=>handler(trusted,JSON.parse(JSON.stringify(request)))}}) });
  const result = await api.getMenu(); assert.equal(result.ok,true);
  assert.deepEqual(JSON.parse(JSON.stringify(result.data.categories.find(c=>c.id==='grill'))), {id:'grill',name:'Grill',parentId:'food'});
  assert.ok(!result.data.categories.some(c=>['hidden','hidden-child','desserts'].includes(c.id)));
  assert.ok(!result.data.products.some(p=>p.id==='hidden-product'));
  assert.equal(handler({},{}).ok,false);
  class Component { setState(update) { Object.assign(this.state, typeof update === 'function' ? update(this.state) : update); } }
  const context = {React:{Component,createElement(){}}, ReactDOM:{createRoot(){return {render(){}}}}, document:{getElementById(){}},window:{arra:{getMenu:()=>Promise.resolve(result),getTables:async()=>({ok:true,data:[]})}},setInterval(){},clearInterval(){},setTimeout(){},clearTimeout(){}};
  vm.runInNewContext(fs.readFileSync(require.resolve('../src/App.js'),'utf8')+'\nthis.Demo=WaiterDemo;',context);
  const app = new context.Demo(); app.componentDidMount(); app.loadDesktopData(); await new Promise(resolve=>setImmediate(resolve));
  const food = app._menu.cats.find(c=>c.id==='food');
  assert.deepEqual(JSON.parse(JSON.stringify(food.subs)), [['food','Food'],['grill','Grill']]);
  assert.ok(!app._menu.cats.some(c=>c.id==='grill'));
  assert.equal(app._menu.byId.steak.cat,'food'); assert.equal(app._menu.byId.steak.sub,'grill');
  assert.equal(app._menu.byId.qebapa.sub,'food'); assert.equal(app.state.sub,'food');
  let view = app.renderVals();
  assert.ok(view.products.some(p => p.name === 'Qebapa'));
  assert.ok(!view.products.some(p => p.name === 'Steak'));
  view.subs.find(s => s.label === 'Grill').pick();
  view = app.renderVals();
  assert.ok(view.products.some(p => p.name === 'Steak'));
  assert.ok(!view.products.some(p => p.name === 'Qebapa'));
  view.onSearch({ target: { value: 'qebapa' } });
  view = app.renderVals();
  assert.ok(view.products.some(p => p.name === 'Qebapa'));
  assert.ok(!view.products.some(p => p.name === 'Steak'));
});
