const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { openDatabase } = require('../src/desktop/database');
const { registerMenuConfig } = require('../src/desktop/menu-config');
const { registerMenu } = require('../src/desktop/menu');
const { registerOrderItems } = require('../src/desktop/order-items');

test('upgrade preserves existing order and direct menu requests handle denial and failed writes', t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'arra-menu-independent-'));
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
  let db = openDatabase(dir);
  db.exec(`DELETE FROM user_permissions WHERE permission IN ('employees.view','employees.change'); DROP TABLE application_audit; DROP TABLE employee_permission_audit; DROP TABLE employee_credential_audit; DROP TABLE employee_account_audit; INSERT INTO local_users (id, username, salt, password_hash) VALUES (10, 'sample-admin', x'00', x'00'), (11, 'sample-staff', x'00', x'00');
    INSERT INTO user_permissions VALUES (10, 'menu.view'), (10, 'orders.view'), (10, 'orders.change'), (11, 'menu.view');
    INSERT INTO dining_areas (id, name) VALUES (1, 'Inside');
    INSERT INTO dining_tables (id, area, area_id) VALUES (1, 'Inside', 1);
    INSERT INTO orders (id, table_id, opened_at, status) VALUES (1, 1, 1, 'open');
    INSERT INTO menu_categories (id, name, active) VALUES ('c', 'Food', 1);
    INSERT INTO menu_products (id, category_id, name, price, active) VALUES ('p', 'c', 'Old name', 123, 1);
    INSERT INTO order_items (order_id, product_id, name, unit_price, quantity, status) VALUES (1, 'p', 'Old name', 123, 1, 'pending');
    ALTER TABLE menu_categories DROP COLUMN parent_id; ALTER TABLE menu_categories DROP COLUMN sort_order; ALTER TABLE menu_products DROP COLUMN sort_order;
    DROP TABLE order_item_modifiers; DROP TABLE modifier_options; DROP TABLE modifier_groups; PRAGMA user_version = 11;`);
  db.close();
  db = openDatabase(dir);
  const handlers = {}, event = {}; let user = 11;
  const ipc = { handle: (channel, handler) => { handlers[channel] = handler; } };
  const session = { currentUserId: () => user, authenticatedUserId: () => user }, allowed = e => e === event;
  registerMenuConfig(ipc, allowed, db, session); registerMenu(ipc, allowed, db, session); registerOrderItems(ipc, allowed, db, session);
  const config = req => handlers['arra:menu-config'](event, req);
  const menu = () => handlers['arra:menu'](event, {});
  const product = {action:'product', id:'p', categoryId:'c', name:'New name', price:456, active:true, sortOrder:2};
  assert.equal(config(product).error, 'Access denied');
  user = null; assert.equal(config(product).error, 'Access denied');
  user = 10; assert.equal(handlers['arra:menu-config']({}, product).ok, false);
  assert.equal(config({...product, categoryId:'missing'}).ok, false);
  assert.equal(config({...product, id:'missing'}).ok, false);
  db.exec("CREATE TRIGGER fail_menu_update BEFORE UPDATE ON menu_products BEGIN SELECT RAISE(ABORT, 'simulated failure'); END");
  assert.deepEqual(config(product), {ok:false, error:'Could not save menu'});
  assert.equal(db.prepare("SELECT name FROM menu_products WHERE id='p'").get().name, 'Old name');
  db.exec('DROP TRIGGER fail_menu_update');
  assert.equal(config(product).ok, true);
  const category = {action:'category', id:null, name:'First', active:true, parentId:null, sortOrder:0};
  assert.equal(config(category).ok, true);
  const first = config({action:'list'}).data.categories.find(c => c.name === 'First');
  assert.equal(config({...product, id:null, name:'First product', sortOrder:0}).ok, true);
  assert.equal(menu().data.categories[0].id, first.id);
  assert.deepEqual(menu().data.products.map(p => p.name), ['First product', 'New name']);
  assert.equal(config({...product, active:false}).ok, true);
  assert.equal(menu().data.products.some(p => p.id === 'p'), false);
  assert.equal(handlers['arra:order-items'](event, {action:'add', orderId:1, productId:'p'}).ok, false);
  db.close(); db = openDatabase(dir);
  assert.deepEqual({...db.prepare('SELECT product_id, name, unit_price, quantity FROM order_items WHERE order_id=1').get()}, {product_id:'p', name:'Old name', unit_price:123, quantity:1});
  assert.equal(db.prepare("SELECT active FROM menu_products WHERE id='p'").get().active, 0);
  db.close();
});
