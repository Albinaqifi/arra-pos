const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { openDatabase } = require('../src/desktop/database');
const { bootstrap, createSession } = require('../src/desktop/session');
const { registerTables, seedTables } = require('../src/desktop/tables');
const { registerMenu, seedMenu } = require('../src/desktop/menu');
const { registerOrders } = require('../src/desktop/orders');
const { registerOrderItems } = require('../src/desktop/order-items');

test('direct operations require current grants, with view distinct from change', t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'arra-permissions-'));
  const db = openDatabase(dir);
  t.after(() => { db.close(); fs.rmSync(dir, { recursive: true, force: true }); });
  bootstrap(db, 'sample', 'sample password'); seedTables(db); seedMenu(db);
  const session = createSession(db); const handlers = {}; const trusted = {};
  const ipc = { handle(channel, fn) { handlers[channel] = fn; } };
  for (const register of [registerTables, registerMenu, registerOrders, registerOrderItems]) register(ipc, e => e === trusted, db, session);
  const invoke = (channel, data) => handlers['arra:' + channel](trusted, data);
  for (const [channel, data] of [['tables', {}], ['menu', {}], ['open-order', { tableId: 1 }], ['order-items', { action: 'list', orderId: 1 }]]) assert.equal(invoke(channel, data).ok, false);
  assert.equal(session.signIn({ username: 'sample', password: 'sample password' }).ok, true);
  assert.equal(invoke('tables', {}).ok, false);
  assert.equal(session.selectWaiter({ id: 1, pin: '' }).ok, true);
  assert.equal(invoke('tables', {}).ok, true); assert.equal(invoke('menu', {}).ok, true);
  const orderId = invoke('open-order', { tableId: 1 }).data.id;
  assert.equal(invoke('order-items', { action: 'add', orderId, productId: 'qebapa' }).ok, true);
  db.prepare("DELETE FROM user_permissions WHERE permission = 'orders.change'").run();
  assert.equal(invoke('order-items', { action: 'list', orderId }).ok, true);
  assert.equal(invoke('open-order', { tableId: 1 }).data.id, orderId);
  assert.equal(invoke('order-items', { action: 'add', orderId, productId: 'qebapa' }).ok, false);
  assert.equal(invoke('open-order', { tableId: 2 }).ok, false);
  assert.equal(db.prepare('SELECT count(*) AS n FROM orders').get().n, 1);
  assert.equal(db.prepare('SELECT count(*) AS n FROM order_items').get().n, 1);
  db.prepare("INSERT INTO user_permissions VALUES (1, 'orders.change')").run();
  db.prepare("DELETE FROM user_permissions WHERE permission = 'orders.view'").run();
  assert.equal(invoke('open-order', { tableId: 1 }).ok, false);
  assert.equal(invoke('order-items', { action: 'list', orderId }).ok, false);
  assert.equal(invoke('order-items', { action: 'add', orderId, productId: 'qebapa' }).ok, false);
  assert.equal(handlers['arra:tables']({}, {}).ok, false);
  db.prepare('UPDATE local_users SET active = 0').run();
  assert.equal(invoke('tables', {}).ok, false);
  db.prepare('UPDATE local_users SET active = 1').run();
  assert.equal(invoke('tables', {}).ok, false);
  assert.equal(session.signIn({ username: 'sample', password: 'sample password' }).ok, true);
  session.signOut(); assert.equal(invoke('tables', {}).ok, false);
});
test('version 8 upgrade grants only the first existing account and preserves it on reopen', t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'arra-permission-upgrade-'));
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
  let db = openDatabase(dir); bootstrap(db, 'sample', 'sample password');
  db.exec("DELETE FROM user_permissions WHERE permission IN ('employees.view','employees.change'); DROP TABLE application_audit; DROP TABLE employee_permission_audit; DROP TABLE employee_credential_audit; DROP TABLE employee_account_audit; INSERT INTO local_users (username, salt, password_hash) VALUES ('other', x'00', x'00'); DROP TABLE user_permissions; ALTER TABLE local_users DROP COLUMN pin_hash; ALTER TABLE local_users DROP COLUMN pin_salt; ALTER TABLE dining_tables DROP COLUMN active; ALTER TABLE dining_tables DROP COLUMN capacity; ALTER TABLE dining_tables DROP COLUMN area_id; DROP TABLE dining_areas; ALTER TABLE menu_categories DROP COLUMN parent_id; ALTER TABLE menu_categories DROP COLUMN sort_order; ALTER TABLE menu_products DROP COLUMN sort_order; DROP TABLE order_item_modifiers; DROP TABLE modifier_options; DROP TABLE modifier_groups; PRAGMA user_version = 8;");
  db.close(); db = openDatabase(dir);
  assert.equal(db.prepare('SELECT count(*) AS n FROM user_permissions WHERE user_id = 1').get().n, 8);
  assert.equal(db.prepare('SELECT count(*) AS n FROM user_permissions WHERE user_id = 2').get().n, 0);
  db.close(); db = openDatabase(dir);
  assert.equal(db.prepare('SELECT count(*) AS n FROM user_permissions').get().n, 8);
  db.close();
});
