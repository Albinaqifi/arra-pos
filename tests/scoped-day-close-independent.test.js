const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { openDatabase } = require('../src/desktop/database');
const { registerBusinessDays } = require('../src/desktop/business-days');
const { registerFinancialVisibility } = require('../src/desktop/financial-visibility');
const { registerTransferCorrection } = require('../src/desktop/transfer-correction');

test('owner close preserves scoped financial visibility, correction cutoff and rollback', async t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'arra-scoped-independent-'));
  const db = openDatabase(dir);
  t.after(() => { db.close(); fs.rmSync(dir, { recursive: true, force: true }); });
  db.exec(`INSERT INTO local_users(id,username,salt,password_hash,pin_salt,pin_hash) VALUES
    (1,'sample-combined',x'01',x'01',NULL,NULL),(2,'sample-a',x'01',x'01',NULL,NULL),
    (3,'sample-b',x'01',x'01',NULL,NULL),(4,'sample-manager',x'01',x'01',x'01',x'01');
    INSERT INTO financial_scopes VALUES(1,'combined'),(2,'A'),(3,'B');
    INSERT INTO user_permissions VALUES(1,'employees.view'),(1,'business_days.close'),(2,'employees.view'),(3,'employees.view');
    INSERT INTO transfer_managers VALUES(4);
    INSERT INTO dining_tables(id,area) VALUES(1,'sample'),(2,'sample'),(3,'sample');
    INSERT INTO orders(id,table_id,opened_at,status) VALUES(1,1,1,'open'),(2,2,1,'open'),(3,3,1,'open');
    INSERT INTO bills(id,order_id,actor_id,generated_at,total,fingerprint) VALUES(1,1,1,1,100,'a'),(2,2,1,1,200,'b'),(3,3,1,1,300,'c');
    INSERT INTO payments(id,bill_id,actor_id,paid_at,amount,method,account) VALUES(1,1,1,1,100,'cash','B'),(2,2,1,2,200,'cash','B'),(3,3,1,3,300,'card','A');`);
  let actor = 4, authenticated = 1, days, financial, transfers, prints = [];
  const session = { currentUserId: () => actor, authenticatedUserId: () => authenticated };
  registerBusinessDays({handle: (_, fn) => days = fn}, e => e.allowed, db, session, job => { prints.push(job); return 'accepted'; });
  registerFinancialVisibility({handle: (_, fn) => financial = fn}, e => e.allowed, db, session);
  registerTransferCorrection({handle: (_, fn) => transfers = fn}, e => e.allowed, db, session);
  const call = (fn, req) => fn({allowed: true}, req);
  assert.equal(call(transfers, {action:'correct',paymentId:1,reason:'sample'}).ok, true);
  actor = authenticated = 2;
  const day = db.prepare('SELECT id FROM business_days WHERE closed_at IS NULL').get().id;
  const report = account => call(financial, {action:'report',from:null,to:null,dayId:day,account,method:null});
  assert.equal(report('B').ok, false);
  assert.equal(call(financial, {action:'detail',paymentId:2}).ok, false);
  assert.deepEqual(report(null).data.records.map(x => x.id), [1,3]);
  assert.equal(report(null).data.corrections, null);
  const detail = call(financial, {action:'detail',paymentId:1}).data;
  assert.equal(detail.payment.account, 'A'); assert.equal(detail.corrections, null);
  assert.equal(Object.hasOwn(detail.payment, 'originalAccount'), false);
  db.exec("CREATE TRIGGER fail_scoped_close BEFORE INSERT ON day_print_attempts BEGIN SELECT RAISE(ABORT,'injected'); END");
  assert.equal(call(days, {action:'close',dayId:day}).ok, false);
  assert.equal(db.prepare('SELECT closed_at FROM business_days WHERE id=?').get(day).closed_at, null);
  assert.equal(db.prepare('SELECT count(*) n FROM day_print_jobs').get().n, 0);
  db.exec('DROP TRIGGER fail_scoped_close');
  assert.equal(call(days, {action:'close',dayId:day}).ok, true);
  assert.equal(call(days, {action:'close',dayId:day}).ok, false);
  await new Promise(resolve => setImmediate(resolve));
  assert.equal(prints.length, 1); assert.equal(prints[0].scope, 'A');
  assert.deepEqual(prints[0].snapshot.records.map(x => x.paymentId), [1,3]);
  assert.equal(prints[0].snapshot.total, 400);
  assert.equal(db.prepare('SELECT count(*) n FROM business_days WHERE closed_at IS NULL').get().n, 1);
  actor = 4; authenticated = 1;
  assert.deepEqual(call(transfers, {action:'list'}).data.payments, []);
  assert.equal(call(transfers, {action:'correct',paymentId:2,reason:'late'}).ok, false);
  actor = authenticated = 3;
  assert.equal(report('A').ok, false);
  assert.equal(call(financial, {action:'detail',paymentId:1}).ok, false);
  assert.deepEqual(report(null).data.records.map(x => x.id), [2]);
  assert.equal(call(days, {action:'retry',dayId:day,requestId:'cross',checked:true,scope:'A'}).ok, false);
  assert.equal(db.prepare('SELECT count(*) n FROM payments').get().n, 3);
  assert.equal(db.prepare('SELECT account FROM payments WHERE id=1').get().account, 'B');
  assert.equal(db.prepare('SELECT count(*) n FROM payment_account_corrections').get().n, 1);
});
