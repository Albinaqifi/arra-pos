// Empty v33 schema generated by eafd3f5, before the v34 printer migration.
function fixture(t) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'arra-upgrade-'));
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
  const file = path.join(dir, 'arra.sqlite');
  fs.writeFileSync(file, zlib.gunzipSync(fs.readFileSync(path.join(__dirname, 'fixtures/s051-v33-empty.sqlite.gz'))));
  const db = authorizedDatabase(new DatabaseSync(file));
  db.exec(`INSERT INTO dining_tables(id,area) VALUES(1,'Sample');
    INSERT INTO menu_categories(id,name,active) VALUES('sample','Sample',1);
    INSERT INTO menu_products(id,category_id,name,price,active,destination) VALUES('p','sample','Sample',100,1,'kitchen');
    INSERT INTO orders(id,table_id,opened_at,status) VALUES(1,1,1,'open');
    INSERT INTO order_items(id,order_id,product_id,name,unit_price,quantity,status,note) VALUES(1,1,'p','Sample',100,2,'sent','sample note');
    INSERT INTO preparation_rounds(id,order_id,request_id,number,actor_id,sent_at,table_id) VALUES(1,1,'round',1,1,2,1);
    INSERT INTO preparation_tickets(id,round_id,destination,adapter) VALUES(1,1,'kitchen','simulated');
    INSERT INTO preparation_ticket_items(ticket_id,item_id,quantity) VALUES(1,1,2);
    INSERT INTO sent_item_corrections(id,request_id,item_id,order_id,actor_id,quantity,reason,occurred_at) VALUES(1,'correction',1,1,1,1,'sample',3);
    INSERT INTO bills(id,order_id,actor_id,generated_at,total,fingerprint) VALUES(1,1,1,4,100,'sample');
    INSERT INTO payments(id,bill_id,actor_id,paid_at,amount,method,account) VALUES(1,1,1,5,100,'cash','B');
    INSERT INTO payment_account_corrections(id,payment_id,actor_id,occurred_at,reason) VALUES(1,1,1,6,'sample');
    INSERT INTO application_audit(actor_id,occurred_at,action,entity_type,entity_id,order_id,context) VALUES(1,7,'sample','order','1',1,'{}');`);
  const before = rows(db); db.close();
  return { dir, file, before };
}
const tables = ['orders','order_items','preparation_rounds','preparation_tickets','preparation_ticket_items','sent_item_corrections','bills','payments','payment_account_corrections','application_audit'];
function rows(db) {
  return Object.fromEntries(tables.map(name => [name, db.prepare(`SELECT * FROM ${name} ORDER BY rowid`).all().map(row => ({ ...row }))]));
}
function check(db, version, before) {
  assert.equal(db.prepare('PRAGMA user_version').get().user_version, version);
  assert.deepEqual(rows(db), before);
  assert.deepEqual(db.prepare('PRAGMA integrity_check').all().map(x => x.integrity_check), ['ok']);
  assert.deepEqual(db.prepare('PRAGMA foreign_key_check').all(), []);
}

test('historical v33 data survives real upgrade and restart', t => {
  const {dir,before} = fixture(t);
  let db = openDatabase(dir); check(db,46,before); db.close();
  db = openDatabase(dir); check(db,46,before); db.close();
});

test('verified pre-upgrade backup restores to an isolated older database', async t => {
  const {dir,before} = fixture(t);
  const parent = fs.mkdtempSync(path.join(os.tmpdir(), 'arra-upgrade-backup-'));
  t.after(() => fs.rmSync(parent, { recursive:true, force:true }));
  const backup = path.join(parent,'backup.enc'), restored = path.join(parent,'restored');
  const secret = require('node:crypto').randomBytes(24).toString('hex');
  await createBackup(dir, backup, secret);
  let db = openDatabase(dir); check(db,46,before); db.close();
  fs.mkdirSync(restored);
  restoreBackup(backup, restored, secret);
  db = new DatabaseSync(path.join(restored,'arra.sqlite')); check(db,33,before); db.close();
  db = openDatabase(restored); check(db,46,before); db.close();
});

test('v42 open-order transition is preserved through restart and backup restore', async t => {
  const {dir} = fixture(t);
  let db = openDatabase(dir);
  db.exec(removeFiscalSchemaSql + `DROP TABLE order_waiter_ownership; DROP TABLE legacy_unassigned_orders;
    INSERT INTO orders(id,table_id,opened_at,status) VALUES(2,1,2,'completed');
    INSERT INTO orders(id,table_id,opened_at,status,retired_empty) VALUES(3,1,3,'open',1);
    PRAGMA user_version=42`);
  const before = rows(db); db.close();
  db = openDatabase(dir); check(db,46,before);
  assert.deepEqual(db.prepare('SELECT order_id FROM legacy_unassigned_orders ORDER BY order_id').all().map(row => row.order_id), [1]);
  assert.equal(db.prepare('SELECT count(*) AS n FROM order_waiter_ownership').get().n, 0);
  db.prepare("INSERT INTO order_waiter_ownership(order_id,waiter_id,assigned_by,assigned_at,source) VALUES(1,1,1,10,'legacy')").run();
  db.close();
  const parent = fs.mkdtempSync(path.join(os.tmpdir(), 'arra-ownership-backup-'));
  t.after(() => fs.rmSync(parent, {recursive:true, force:true}));
  const backup = path.join(parent,'backup.enc'), restored = path.join(parent,'restored');
  const secret = require('node:crypto').randomBytes(24).toString('hex');
  await createBackup(dir, backup, secret);
  fs.mkdirSync(restored); restoreBackup(backup, restored, secret);
  db = openDatabase(restored); check(db,46,before);
  assert.deepEqual({...db.prepare('SELECT order_id,waiter_id,assigned_by,assigned_at,source FROM order_waiter_ownership').get()},
    {order_id:1,waiter_id:1,assigned_by:1,assigned_at:10,source:'legacy'});
  assert.deepEqual(db.prepare('SELECT order_id FROM legacy_unassigned_orders').all().map(row => row.order_id), [1]);
  db.close();
});

test('SQLite full during migration is visible and rolls back; retry preserves history', t => {
  const {dir,file,before} = fixture(t);
  let db = new DatabaseSync(file);
  const pages = db.prepare('PRAGMA page_count').get().page_count;
  db.exec(`PRAGMA max_page_count=${pages}`);
  assert.throws(() => migrate(db), /full/i);
  check(db,33,before); db.close();
  db = openDatabase(dir); check(db,46,before); db.close();
});

test('process termination during migration recovers original and permits retry', t => {
  const {dir,file,before} = fixture(t);
  const program = `const {DatabaseSync}=require('node:sqlite'); const {migrate}=require(${JSON.stringify(path.resolve(__dirname,'../src/desktop/database'))}); const db=new DatabaseSync(process.argv[1]); const proxy={prepare:db.prepare.bind(db), get isTransaction(){return db.isTransaction}, exec(sql){db.exec(sql); if(sql.startsWith('INSERT INTO s075_new SELECT')) process.exit(73)}}; migrate(proxy);`;
  const child = spawnSync(process.execPath, ['-e',program,file], { encoding:'utf8' });
  assert.equal(child.status,73,child.stderr);
  let db = new DatabaseSync(file); check(db,33,before); db.close();
  db = openDatabase(dir); check(db,46,before); db.close();
});
