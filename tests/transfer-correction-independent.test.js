const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { openDatabase } = require('../src/desktop/database');
const { registerTransferCorrection } = require('../src/desktop/transfer-correction');
const { registerFinancialVisibility } = require('../src/desktop/financial-visibility');
const { registerBusinessDays } = require('../src/desktop/business-days');
const { bootstrap, createSession } = require('../src/desktop/session');
const { createSampleTransferManager } = require('../src/desktop/sample-transfer-manager');
const { hasPermissions } = require('../src/desktop/permissions');
const { randomBytes, randomInt } = require('node:crypto');

test('upgraded data, restricted requests, failure rollback and account visibility', t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'arra-transfer-independent-'));
  let db = openDatabase(dir);
  t.after(() => { db.close(); fs.rmSync(dir, { recursive: true, force: true }); });
  db.exec(`INSERT INTO local_users(id,username,salt,password_hash,pin_salt,pin_hash) VALUES
    (1,'manager',x'01',x'01',x'01',x'01'), (2,'admin',x'01',x'01',NULL,NULL);
    INSERT INTO financial_scopes VALUES(2,'combined');
    INSERT INTO user_permissions VALUES(2,'employees.view');
    INSERT INTO dining_tables(id,area,active) VALUES(1,'inactive',0),(2,'active',1),(3,'active',1);
    INSERT INTO orders(id,table_id,opened_at,status) VALUES(1,1,1,'open'),(2,2,1,'open'),(3,3,1,'open');
    INSERT INTO bills(id,order_id,actor_id,generated_at,total,fingerprint) VALUES(1,1,2,1,100,'a'),(2,2,2,1,200,'b'),(3,3,2,1,300,'c');
    INSERT INTO payments(id,bill_id,actor_id,paid_at,amount,method,account) VALUES(1,1,2,1,100,'cash','B'),(2,2,2,1,200,'cash','A'),(3,3,2,1,300,'card','A');
    UPDATE orders SET status='completed';
    DROP TRIGGER payment_corrections_no_replace; DROP TRIGGER payment_corrections_no_delete;
    DROP TRIGGER payment_corrections_no_update; DROP TRIGGER payment_correction_validate;
    DROP TABLE payment_account_corrections; DROP TABLE transfer_managers; DROP INDEX one_open_order_per_table; ALTER TABLE orders DROP COLUMN retired_empty; CREATE UNIQUE INDEX one_open_order_per_table ON orders(table_id) WHERE status=char(111,112,101,110); DROP TABLE IF EXISTS test_print_results; DROP TABLE IF EXISTS test_print_attempts; DROP TABLE IF EXISTS test_print_jobs; DROP TABLE IF EXISTS test_printer_queues; DROP TABLE IF EXISTS day_print_settings; DROP TABLE IF EXISTS day_print_results; DROP TABLE IF EXISTS day_print_attempts; DROP TABLE IF EXISTS day_print_jobs; DROP TABLE IF EXISTS pending_staff; PRAGMA user_version=23;`);
  db.close(); db = openDatabase(dir);
  assert.equal(db.prepare('PRAGMA user_version').get().user_version, 29);
  assert.equal(db.prepare('SELECT count(*) n FROM payments').get().n, 3);
  db.prepare('INSERT INTO transfer_managers VALUES(1)').run();
  let current = 1, authenticated = 2, transfer, financial;
  const session = { currentUserId: () => current, authenticatedUserId: () => authenticated };
  registerTransferCorrection({handle: (_, fn) => transfer = fn}, e => e.allowed, db, session);
  registerFinancialVisibility({handle: (_, fn) => financial = fn}, e => e.allowed, db, session);
  const call = request => transfer({allowed:true}, request);
  assert.equal(transfer({allowed:false}, {action:'list'}).ok, false);
  authenticated = null; assert.equal(call({action:'list'}).ok, false); authenticated = 2;
  current = 2; assert.equal(call({action:'correct',paymentId:1,reason:'sample'}).ok, false); current = 1;
  for (const req of [null, {}, {action:'correct',paymentId:0,reason:''}, {action:'correct',paymentId:2,reason:'A to B'}, {action:'correct',paymentId:3,reason:'card'}, {action:'correct',paymentId:1,reason:'x',account:'B'}]) assert.equal(call(req).ok, false);
  const eligible = call({action:'list'}).data;
  assert.deepEqual(eligible.payments.map(p => p.id), [1]);
  assert.ok(eligible.tables.some(table => table.id === 1), 'eligible payment on inactive table must be reachable');
  db.exec("CREATE TRIGGER fail_audit BEFORE INSERT ON application_audit WHEN NEW.action='correct_account' BEGIN SELECT RAISE(ABORT,'injected'); END");
  assert.equal(call({action:'correct',paymentId:1,reason:' sample '}).ok, false);
  assert.equal(db.prepare('SELECT count(*) n FROM payment_account_corrections').get().n, 0);
  db.exec('DROP TRIGGER fail_audit');
  assert.equal(call({action:'correct',paymentId:1,reason:' sample '}).ok, true);
  assert.equal(call({action:'correct',paymentId:1,reason:'sample'}).ok, false);
  const row = db.prepare('SELECT * FROM payment_account_corrections').get();
  assert.equal(row.actor_id, 1); assert.ok(row.occurred_at > 0); assert.equal(row.reason, 'sample');
  assert.equal(db.prepare('SELECT account FROM payments WHERE id=1').get().account, 'B');
  current = authenticated = 2;
  const aggregate = account => ({...financial({allowed:true},{action:'aggregate',account}).data});
  assert.deepEqual(aggregate(null), {count:3,total:600});
  assert.deepEqual(aggregate('A'), {count:3,total:600});
  assert.deepEqual(aggregate('B'), {count:0,total:0});
  db.prepare("UPDATE financial_scopes SET scope='B' WHERE user_id=2").run();
  assert.equal(financial({allowed:true},{action:'detail',paymentId:1}).ok, false);
  db.prepare("UPDATE financial_scopes SET scope='A' WHERE user_id=2").run();
  assert.equal(financial({allowed:true},{action:'detail',paymentId:1}).data.payment.account, 'A');
  db.close(); db = openDatabase(dir);
  assert.equal(db.prepare('SELECT count(*) n FROM payment_account_corrections').get().n, 1);
});

test('real close prevents later corrections and manager is isolated after separate PIN authentication', t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'arra-transfer-close-'));
  const db = openDatabase(dir);
  t.after(() => { db.close(); fs.rmSync(dir, { recursive: true, force: true }); });
  const password = randomBytes(24).toString('hex');
  const pin = String(randomInt(10000)).padStart(4, '0');
  bootstrap(db, 'sample-admin', password);
  db.exec("UPDATE financial_scopes SET scope='combined' WHERE user_id=1; INSERT OR IGNORE INTO user_permissions VALUES(1,'business_days.close');");
  const manager = createSampleTransferManager(db, pin);
  db.exec(`INSERT INTO dining_tables(id,area) VALUES(1,'sample');
    INSERT INTO orders(id,table_id,opened_at,status) VALUES(1,1,1,'open');
    INSERT INTO bills(id,order_id,actor_id,generated_at,total,fingerprint) VALUES(1,1,1,1,100,'a');
    INSERT INTO payments(id,bill_id,actor_id,paid_at,amount,method,account) VALUES(1,1,1,1,100,'cash','B');
    UPDATE orders SET status='completed';`);
  const session = createSession(db); let transfer, days;
  registerTransferCorrection({handle: (_, fn) => transfer = fn}, () => true, db, session);
  registerBusinessDays({handle: (_, fn) => days = fn}, () => true, db, session);
  assert.equal(transfer({}, {action:'list'}).ok, false);
  assert.equal(session.signIn({username:'sample-admin',password}).ok, true);
  const wrong = String((Number(pin)+1)%10000).padStart(4,'0');
  assert.equal(session.selectWaiter({id:manager,pin:wrong}).ok, false);
  assert.equal(transfer({}, {action:'list'}).ok, false);
  assert.equal(session.selectWaiter({id:manager,pin}).ok, true);
  assert.deepEqual(transfer({}, {action:'list'}).data.payments.map(p => p.id), [1]);
  for (const permission of ['tables.view','orders.change','employees.view','employees.change','business_days.close']) assert.equal(hasPermissions(db,session,permission), false);
  assert.equal(days({}, {action:'list'}).ok, false);
  assert.equal(session.selectWaiter({id:1,pin:''}).ok, true);
  const dayId = days({}, {action:'list'}).data.days[0].id;
  assert.equal(days({}, {action:'close',dayId}).ok, true);
  assert.equal(session.selectWaiter({id:manager,pin}).ok, true);
  assert.deepEqual(transfer({}, {action:'list'}).data.payments, []);
  assert.equal(transfer({}, {action:'correct',paymentId:1,reason:'sample'}).ok, false);
  assert.equal(db.prepare('SELECT count(*) n FROM payment_account_corrections').get().n, 0);
  assert.equal(db.prepare('SELECT account FROM payments WHERE id=1').get().account, 'B');
});
