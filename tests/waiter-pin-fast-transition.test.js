const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { randomBytes, randomInt } = require('node:crypto');
const { openDatabase } = require('../src/desktop/database');
const { seedSampleIdentities } = require('../src/desktop/sample-accounts');
const { createSession, hashPassword } = require('../src/desktop/session');
const { registerEmployeeConfig } = require('../src/desktop/employee-config');

test('hashed and direct waiter credentials transition safely, including same-PIN reset and rollback', t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'arra-pin-format-'));
  let db = openDatabase(dir);
  t.after(() => { db.close(); fs.rmSync(dir, { recursive: true, force: true }); });
  const secret = () => randomBytes(24).toString('hex');
  const passwords = Array.from({ length: 4 }, secret);
  const firstPin = '0' + String(randomInt(1000)).padStart(3, '0');
  const secondPin = '1' + String(randomInt(1000)).padStart(3, '0');
  const managerPin = String(randomInt(1000000)).padStart(6, '0');
  seedSampleIdentities(db, passwords, firstPin, managerPin);
  const first = db.prepare("SELECT id FROM local_users WHERE username='sample-waiter'").get().id;
  const manager = db.prepare('SELECT user_id AS id FROM transfer_managers').get().id;
  const salt = randomBytes(16);
  db.prepare('UPDATE local_users SET pin_salt=?, pin_hash=? WHERE id=?').run(salt, hashPassword(firstPin, salt), first);
  let session, call;
  const connect = () => {
    session = createSession(db);
    const handlers = {}, trusted = {};
    registerEmployeeConfig({ handle(name, fn) { handlers[name] = fn; } }, event => event === trusted, db, session);
    call = req => handlers['arra:employee-config'](trusted, req);
  };
  const signIn = (index, name) => assert.equal(session.signIn({ username: name, password: passwords[index] }).ok, true);
  const identify = pin => session.identifyStaff({ kind: 'waiter', pin });
  connect();
  signIn(0, 'sample-restaurant');
  assert.equal(identify(firstPin).data.id, first, 'existing hashed PIN still works');
  signIn(3, 'sample-combined');
  assert.equal(call({ action: 'create', username: 'other', password: secret(), pin: firstPin }).ok, false, 'legacy hash reserves its PIN');
  assert.equal(call({ action: 'create', username: 'other', password: secret(), pin: secondPin }).ok, true);
  const second = db.prepare("SELECT id FROM local_users WHERE username='other'").get().id;
  assert.equal(call({ action: 'credential', id: first, password: null, pin: secondPin }).ok, false, 'direct PIN also reserves its value');
  db.exec("CREATE TRIGGER fail_fast_pin_audit BEFORE INSERT ON employee_credential_audit BEGIN SELECT RAISE(ABORT, 'failure'); END");
  assert.equal(call({ action: 'credential', id: first, password: null, pin: firstPin }).ok, false);
  assert.deepEqual(Buffer.from(db.prepare('SELECT pin_salt FROM local_users WHERE id=?').get(first).pin_salt), salt, 'failure leaves legacy credential intact');
  db.exec('DROP TRIGGER fail_fast_pin_audit');
  assert.equal(call({ action: 'credential', id: first, password: null, pin: firstPin }).ok, true, 'same PIN can be reset');
  assert.equal(db.prepare('SELECT length(pin_salt) AS n FROM local_users WHERE id=?').get(first).n, 0);
  assert.ok(db.prepare('SELECT length(pin_salt) AS n FROM local_users WHERE id=?').get(manager).n > 0, 'manager remains hashed');
  db.close(); db = openDatabase(dir); connect();
  signIn(0, 'sample-restaurant');
  assert.equal(identify(firstPin).data.id, first);
  assert.equal(identify(secondPin).data.id, second);
  assert.equal(session.identifyStaff({ kind: 'transfer', pin: managerPin }).data.id, manager);
  db.prepare('UPDATE local_users SET active=0 WHERE id=?').run(first);
  assert.equal(identify(firstPin).ok, false);
  signIn(3, 'sample-combined');
  assert.equal(call({ action: 'credential', id: second, password: null, pin: firstPin }).ok, false, 'inactive waiter still reserves PIN');
  db.prepare('UPDATE local_users SET active=1 WHERE id=?').run(first);
  db.prepare('UPDATE local_users SET pin_hash=? WHERE id=?').run(Buffer.from('oops'), second);
  signIn(0, 'sample-restaurant');
  assert.equal(identify(firstPin).ok, false, 'malformed active waiter credential fails closed');
  assert.equal(session.currentUserId(), null);
  signIn(3, 'sample-combined');
  assert.equal(call({ action: 'credential', id: second, password: null, pin: secondPin }).ok, true);
  signIn(0, 'sample-restaurant');
  assert.equal(identify(firstPin).data.id, first);
});
