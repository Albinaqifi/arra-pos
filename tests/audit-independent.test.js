const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { openDatabase } = require('../src/desktop/database');
const { seedTables } = require('../src/desktop/tables');
const { registerOrders } = require('../src/desktop/orders');
const { registerEmployeeConfig } = require('../src/desktop/employee-config');
const { DatabaseSync } = require('node:sqlite');

test('audit failures roll back order and employee creation; denied requests leave no history', t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'arra-audit-independent-'));
  const db = openDatabase(dir);
  t.after(() => { db.close(); fs.rmSync(dir, { recursive: true, force: true }); });
  seedTables(db);
  db.exec("INSERT INTO local_users (id,username,salt,password_hash) VALUES (1,'admin',x'00',x'00'), (2,'waiter',x'00',x'00'); INSERT INTO user_permissions VALUES (1,'orders.view'),(1,'orders.change'),(1,'employees.change'),(2,'orders.view');");
  let actor = 1; const session = { currentUserId: () => actor, authenticatedUserId: () => actor };
  const trusted = {}, handlers = {};
  const ipc = { handle: (channel, fn) => { handlers[channel] = fn; } };
  registerOrders(ipc, e => e === trusted, db, session);
  registerEmployeeConfig(ipc, e => e === trusted, db, session);
  const open = () => handlers['arra:open-order'](trusted, { tableId: 1 });
  const create = () => handlers['arra:employee-config'](trusted, { action: 'create', username: 'new staff', password: 'sample password', pin: '3141' });
  db.exec("CREATE TRIGGER fail_audit BEFORE INSERT ON application_audit BEGIN SELECT RAISE(ABORT, 'failure'); END;");
  assert.equal(open().ok, false);
  assert.equal(create().ok, false);
  assert.equal(db.prepare('SELECT count(*) AS n FROM orders').get().n, 0);
  assert.equal(db.prepare('SELECT count(*) AS n FROM local_users').get().n, 2);
  assert.equal(db.prepare('SELECT count(*) AS n FROM application_audit').get().n, 0);
  db.exec('DROP TRIGGER fail_audit');
  actor = 2;
  assert.equal(open().ok, false);
  assert.equal(create().ok, false);
  assert.equal(handlers['arra:employee-config'](trusted, { action: 'delete-audit', id: 1 }).ok, false);
  assert.equal(db.prepare('SELECT count(*) AS n FROM application_audit').get().n, 0);
  actor = 1;
  assert.equal(open().ok, true);
  assert.equal(create().ok, true);
  const rows = db.prepare('SELECT * FROM application_audit ORDER BY id').all();
  assert.deepEqual(rows.map(r => r.action), ['open', 'create']);
  assert.ok(rows.every(r => r.actor_id === 1 && r.occurred_at > 0));
  assert.equal(JSON.stringify(rows).includes('sample password'), false);
  assert.equal(JSON.stringify(rows).includes('3141'), false);
});

test('failed version 15 migration preserves version 14 data and can be retried', t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'arra-audit-migration-'));
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
  let db = openDatabase(dir);
  db.exec("INSERT INTO app_metadata(key,value) VALUES('sample','retained'); DROP TABLE application_audit; DROP TRIGGER employee_permission_audit_no_replace; DROP TRIGGER employee_account_audit_no_replace; DROP TRIGGER employee_credential_audit_no_replace; CREATE TRIGGER application_audit_no_update AFTER INSERT ON app_metadata BEGIN SELECT 1; END; DROP TABLE print_attempts; DROP TABLE print_jobs; DROP TABLE simulated_printers; DROP TABLE preparation_ticket_items; DROP TABLE preparation_tickets; DROP TABLE preparation_rounds; ALTER TABLE menu_products DROP COLUMN destination; PRAGMA user_version = 14;");
  db.close();
  assert.throws(() => openDatabase(dir));
  db = new DatabaseSync(path.join(dir, 'arra.sqlite'));
  assert.equal(db.prepare('PRAGMA user_version').get().user_version, 14);
  assert.equal(db.prepare("SELECT value FROM app_metadata WHERE key='sample'").get().value, 'retained');
  assert.equal(db.prepare("SELECT count(*) AS n FROM sqlite_master WHERE type='table' AND name='application_audit'").get().n, 0);
  db.exec('DROP TRIGGER application_audit_no_update');
  db.close();
  db = openDatabase(dir);
  assert.equal(db.prepare('PRAGMA user_version').get().user_version, 18);
  assert.equal(db.prepare("SELECT value FROM app_metadata WHERE key='sample'").get().value, 'retained');
  db.close();
});
