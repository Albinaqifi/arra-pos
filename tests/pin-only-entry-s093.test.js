const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { randomBytes, randomInt } = require('node:crypto');
const { openDatabase } = require('../src/desktop/database');
const { registerSession, hashPassword } = require('../src/desktop/session');
const { seedSampleIdentities } = require('../src/desktop/sample-accounts');
const { seedTables } = require('../src/desktop/tables');

test('PIN-only entry requires one verified active waiter or one active transfer manager', t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'arra-pin-entry-'));
  let db = openDatabase(dir);
  t.after(() => { db.close(); fs.rmSync(dir, {recursive:true,force:true}); });
  const secret = () => randomBytes(24).toString('hex');
  const passwords = Array.from({length:4},secret);
  const waiterPin = '0' + String(randomInt(1000)).padStart(3,'0');
  const managerPin = '0' + String(randomInt(100000)).padStart(5,'0');
  seedSampleIdentities(db,passwords,waiterPin,managerPin);
  seedTables(db);
  let handlers, session;
  const trusted = {}, untrusted = {};
  const connect = () => { handlers = {}; session = registerSession({handle:(name,fn)=>{handlers[name]=fn;}}, event=>event===trusted,db); };
  const call = (channel, req, event=trusted) => handlers['arra:'+channel](event,req);
  connect();
  assert.equal(call('entry-tables',{}).ok,false);
  assert.equal(call('identify-staff',{kind:'waiter',pin:waiterPin}).ok,false);
  assert.equal(call('sign-in',{username:'sample-restaurant',password:passwords[0]}).ok,true);
  assert.equal(call('waiters',{}).ok,false, 'old roster IPC is unavailable before identification');
  const grid = call('entry-tables',{});
  assert.equal(grid.ok,true); assert.ok(grid.data.length);
  assert.deepEqual(Object.keys(grid.data[0]).sort(),['area','id','occupied','waiter']);
  assert.equal(grid.data[0].waiter,null);
  const waiterId=db.prepare("SELECT id FROM local_users WHERE username='sample-waiter'").get().id;
  const insertOrder=db.prepare("INSERT INTO orders(table_id,opened_at,status) VALUES(?,1,'open')");
  const owned=insertOrder.run(1).lastInsertRowid, legacy=insertOrder.run(2).lastInsertRowid, untouched=insertOrder.run(3).lastInsertRowid;
  db.prepare("INSERT INTO order_waiter_ownership VALUES(?,?,?,1,'open')").run(owned,waiterId,waiterId);
  db.prepare("INSERT INTO order_waiter_ownership VALUES(?,?,?,1,'open')").run(untouched,waiterId,waiterId);
  db.prepare("INSERT INTO application_audit(actor_id,occurred_at,action,entity_type,entity_id,order_id,context) VALUES(?,1,'open','order',?,?,'{}')").run(waiterId,String(untouched),untouched);
  let entry=call('entry-tables',{}).data;
  assert.deepEqual(entry.find(row=>row.id===1),{id:1,area:'Inside',occupied:true,waiter:'sample-waiter'});
  assert.deepEqual(entry.find(row=>row.id===2),{id:2,area:'Inside',occupied:true,waiter:null},'legacy orders do not infer an owner');
  assert.deepEqual(entry.find(row=>row.id===3),{id:3,area:'Inside',occupied:false,waiter:null},'untouched orders remain free');
  db.prepare('UPDATE orders SET table_id=4 WHERE id=?').run(owned);
  entry=call('entry-tables',{}).data;
  assert.equal(entry.find(row=>row.id===1).waiter,null);
  assert.equal(entry.find(row=>row.id===4).waiter,'sample-waiter','a moved order keeps its assigned waiter');
  db.prepare("UPDATE orders SET status='completed' WHERE id IN (?,?,?)").run(owned,legacy,untouched);
  assert.equal(call('entry-tables',{}).data.find(row=>row.id===4).waiter,null,'a closed order is not inherited');
  assert.equal(call('entry-tables',{},untrusted).ok,false);
  assert.equal(call('entry-tables',{extra:true}).ok,false);
  assert.equal(call('identify-staff',{kind:'waiter',pin:waiterPin},untrusted).ok,false);
  assert.equal(call('identify-staff',{kind:'transfer',pin:waiterPin}).ok,false);
  assert.equal(call('identify-staff',{kind:'waiter',pin:managerPin}).ok,false);
  const first=call('identify-staff',{kind:'waiter',pin:waiterPin});
  assert.equal(first.ok,true); assert.equal(first.data.isTransfer,false); assert.equal(session.currentUserId(),first.data.id);
  assert.equal(call('entry-tables',{}).ok,false, 'entry grid is limited to pre-identity session');
  assert.equal(call('identify-staff',{kind:'waiter',pin:'wrong'}).ok,false);
  assert.equal(session.currentUserId(),null, 'failed switch clears old selected actor');
  assert.equal(call('identify-staff',{kind:'waiter',pin:waiterPin}).ok,true);
  assert.equal(call('select-waiter',{id:first.data.id,pin:waiterPin}).ok,false, 'old IPC cannot bypass PIN-only verification');
  assert.equal(session.currentUserId(),null, 'obsolete selection cannot leave an old actor active');
  const manager=call('identify-staff',{kind:'transfer',pin:managerPin});
  assert.equal(manager.ok,true); assert.equal(manager.data.isTransfer,true);
  assert.equal(call('entry-tables',{}).ok,false);
  assert.equal(call('identify-staff',{kind:'waiter',pin:waiterPin,extra:1}).ok,false);
  assert.equal(session.currentUserId(),null);

  // A legacy active duplicate must make a verified credential ambiguous.
  const salt=randomBytes(16), pinSalt=randomBytes(16);
  const duplicate=db.prepare('INSERT INTO local_users(username,salt,password_hash,pin_salt,pin_hash) VALUES(?,?,?,?,?)').run('legacy',salt,hashPassword(secret(),salt),pinSalt,hashPassword(waiterPin,pinSalt)).lastInsertRowid;
  db.prepare("INSERT INTO financial_scopes VALUES(?,'waiter')").run(duplicate);
  assert.equal(call('identify-staff',{kind:'waiter',pin:waiterPin}).ok,false);
  db.prepare('UPDATE local_users SET active=0 WHERE id=?').run(duplicate);
  assert.equal(call('identify-staff',{kind:'waiter',pin:waiterPin}).ok,true);
  db.prepare('DELETE FROM verified_waiter_pins WHERE user_id=?').run(first.data.id);
  assert.equal(call('identify-staff',{kind:'waiter',pin:waiterPin}).ok,false, 'unverified legacy match requires reset');
  db.prepare('INSERT INTO verified_waiter_pins VALUES(?)').run(first.data.id);
  const duplicateManagerSalt=randomBytes(16);
  const duplicateManager=db.prepare('INSERT INTO local_users(username,salt,password_hash,pin_salt,pin_hash) VALUES(?,?,?,?,?)').run('legacy manager',salt,hashPassword(secret(),salt),duplicateManagerSalt,hashPassword(managerPin,duplicateManagerSalt)).lastInsertRowid;
  db.prepare('INSERT INTO transfer_managers VALUES(?)').run(duplicateManager);
  assert.equal(call('identify-staff',{kind:'transfer',pin:managerPin}).ok,false);
  db.prepare('UPDATE local_users SET active=0 WHERE id=?').run(duplicateManager);
  assert.equal(call('identify-staff',{kind:'transfer',pin:managerPin}).ok,true);
  db.close(); db=openDatabase(dir); connect();
  assert.equal(call('sign-in',{username:'sample-restaurant',password:passwords[0]}).ok,true);
  assert.equal(call('identify-staff',{kind:'waiter',pin:waiterPin}).ok,true);
  assert.equal(call('sign-in',{username:'sample-combined',password:passwords[3]}).ok,true);
  const owner=session.currentUserId();
  assert.equal(call('identify-staff',{kind:'waiter',pin:waiterPin}).ok,false);
  assert.equal(session.currentUserId(),owner, 'owner identity survives rejected staff entry');
  assert.equal(call('entry-tables',{}).ok,false);
});
