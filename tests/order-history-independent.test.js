const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { openDatabase } = require('../src/desktop/database');
const { authorizedDatabase } = require('./support/authorized-database');
const { seedTables } = require('../src/desktop/tables');
const { seedMenu } = require('../src/desktop/menu');
const { registerOrderItems } = require('../src/desktop/order-items');
const { registerPrintJobs } = require('../src/desktop/print-jobs');
const { registerOrderHistory } = require('../src/desktop/order-history');
const { recordAudit } = require('../src/desktop/audit');

test('history preserves simulated failed, uncertain and successful print attempts and excludes financial audit data', t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'arra-history-independent-'));
  const db = authorizedDatabase(openDatabase(dir));
  t.after(() => { db.close(); fs.rmSync(dir, { recursive: true, force: true }); });
  seedTables(db); seedMenu(db);
  db.exec("INSERT INTO user_permissions VALUES(1,'employees.view'); INSERT INTO orders(table_id,opened_at,status) VALUES(1,1,'open')");
  const event = {}, handlers = {}, ipc = { handle: (name, fn) => { handlers[name] = fn; } };
  const session = { currentUserId: () => 1, authenticatedUserId: () => 1 };
  for (const register of [registerOrderItems, registerPrintJobs, registerOrderHistory]) register(ipc, e => e === event, db, session);
  const items = request => handlers['arra:order-items'](event, request);
  const jobs = request => handlers['arra:print-jobs'](event, request);
  const history = () => handlers['arra:order-history'](event, { orderId: 1 });
  assert.equal(jobs({ action: 'simulate', destination: 'kitchen', result: 'failed' }).ok, true);
  assert.equal(items({ action: 'add', orderId: 1, productId: 'qebapa' }).ok, true);
  assert.equal(items({ action: 'send', orderId: 1, requestId: 'send' }).ok, true);
  const jobId = jobs({ action: 'list' }).data.jobs[0].id;
  assert.equal(jobs({ action: 'simulate', destination: 'kitchen', result: 'uncertain' }).ok, true);
  assert.equal(jobs({ action: 'retry', jobId, requestId: 'retry-1' }).ok, true);
  assert.equal(jobs({ action: 'retry', jobId, requestId: 'retry-1' }).ok, true);
  assert.equal(jobs({ action: 'simulate', destination: 'kitchen', result: 'success' }).ok, true);
  assert.equal(jobs({ action: 'retry', jobId, requestId: 'retry-2' }).ok, true);
  recordAudit(db, 1, 'payment', 'payment', 1, 1, { account: 'B', amount: 987654 });
  recordAudit(db, 1, 'add', 'order_item', 1, 1, { name: 'sample', quantity: 1, account: 'B', amount: 987654 });
  const result = history(); assert.equal(result.ok, true);
  const attempts = result.data.events.filter(e => e.action === 'print_attempt');
  assert.deepEqual(attempts.map(e => e.result).sort(), ['failed', 'success', 'uncertain']);
  assert.ok(attempts.every(e => e.actor && e.occurredAt && e.adapter === 'simulated'));
  const json = JSON.stringify(result);
  assert.equal(json.includes('987654'), false);
  assert.equal(json.includes('"account"'), false);
  assert.equal(result.data.events.some(e => e.action === 'payment'), false);
});
