const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { openDatabase } = require('../src/desktop/database');
const { authorizedDatabase } = require('./support/authorized-database');
const { seedTables } = require('../src/desktop/tables');
const { registerPayments } = require('../src/desktop/payments');
const { registerTestPrinting } = require('../src/desktop/test-printing');

test('lost response and interrupted output retain one payment and require checked recovery after reopen', async t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'arra-s083-independent-'));
  let db = authorizedDatabase(openDatabase(dir));
  t.after(() => { db.close(); fs.rmSync(dir, { recursive: true, force: true }); });
  seedTables(db);
  db.exec("INSERT INTO local_users(id,username,salt,password_hash) VALUES(2,'scope-a',x'00',x'00'),(3,'scope-b',x'00',x'00'); INSERT INTO financial_scopes VALUES(2,'A'),(3,'B'); INSERT INTO user_permissions VALUES(2,'employees.view'),(3,'employees.view'); INSERT INTO orders(id,table_id,opened_at,status) VALUES(1,1,1,'open'); INSERT INTO order_waiter_ownership SELECT id,1,1,1,'open' FROM orders WHERE id NOT IN (SELECT order_id FROM order_waiter_ownership); INSERT INTO bills(id,order_id,actor_id,generated_at,total,fingerprint) VALUES(1,1,1,1,100,'sample'); UPDATE bill_printer_queues SET queue='Queue B' WHERE account='B';");
  let actor = 1, pay, jobs, calls = 0;
  const session = { currentUserId: () => actor, authenticatedUserId: () => actor };
  const register = () => {
    registerPayments({ handle: (_, f) => { pay = f; } }, () => true, db, session, () => { calls++; throw Error('interrupted'); });
    registerTestPrinting({ handle: (_, f) => { jobs = f; } }, () => true, db, session, () => { calls++; return 'accepted'; }, true);
  };
  register();
  const payment = { billId: 1, method: 'cash', account: 'B' };
  assert.equal(pay({}, { ...payment, method: 'card' }).ok, false);
  assert.equal(pay({}, payment).ok, true); // Treat the successful response as lost.
  assert.equal(pay({}, payment).ok, true);
  assert.equal(pay({}, { ...payment, account: 'A' }).ok, false);
  await new Promise(setImmediate);
  assert.equal(calls, 1);
  db.close(); db = authorizedDatabase(openDatabase(dir)); register();
  assert.equal(pay({}, payment).ok, true);
  assert.equal(db.prepare('SELECT count(*) AS n FROM payments').get().n, 1);
  assert.equal(db.prepare('SELECT status FROM orders WHERE id=1').get().status, 'completed');
  actor = 2;
  assert.equal(jobs({}, { action: 'list' }).data.jobs.length, 0);
  const jobId = db.prepare('SELECT id FROM test_print_jobs WHERE bill_id=1').get().id;
  assert.equal(jobs({}, { action: 'retry', jobId, requestId: 'denied', checked: true }).ok, false);
  actor = 3;
  const job = jobs({}, { action: 'list' }).data.jobs.find(j => j.id === jobId);
  assert.equal(job.result, 'uncertain');
  assert.equal(job.attempts, 1);
  assert.equal(job.queue, 'Queue B');
  assert.equal(jobs({}, { action: 'retry', jobId, requestId: 'recover', checked: false }).ok, false);
  assert.equal(jobs({}, { action: 'retry', jobId, requestId: 'recover', checked: true }).ok, true);
  await new Promise(setImmediate);
  assert.equal(jobs({}, { action: 'retry', jobId, requestId: 'recover', checked: true }).ok, true);
  await new Promise(setImmediate);
  assert.equal(calls, 2);
  assert.equal(db.prepare('SELECT count(*) AS n FROM test_print_attempts WHERE job_id=?').get(jobId).n, 2);
});

test('bill-only mode allows authorized bill recovery but denies preparation operations', async t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'arra-s083-bill-only-'));
  const db = authorizedDatabase(openDatabase(dir));
  t.after(() => { db.close(); fs.rmSync(dir, { recursive: true, force: true }); });
  seedTables(db);
  db.exec("INSERT INTO local_users(id,username,salt,password_hash) VALUES(2,'admin',x'00',x'00'),(3,'limited',x'00',x'00'); INSERT INTO financial_scopes VALUES(2,'combined'),(3,'A'); INSERT INTO user_permissions VALUES(2,'employees.view'),(2,'employees.change'),(3,'employees.view'); INSERT INTO orders(id,table_id,opened_at,status) VALUES(1,1,1,'open'); INSERT INTO order_waiter_ownership SELECT id,1,1,1,'open' FROM orders WHERE id NOT IN (SELECT order_id FROM order_waiter_ownership); INSERT INTO bills(id,order_id,actor_id,generated_at,total,fingerprint) VALUES(1,1,1,1,100,'sample'); INSERT INTO preparation_rounds(id,order_id,request_id,number,actor_id,sent_at,table_id) VALUES(1,1,'round',1,1,1,1); INSERT INTO preparation_tickets(id,round_id,destination,adapter) VALUES(1,1,'kitchen','simulated'); INSERT INTO test_print_jobs(destination,ticket_id,snapshot,created_at) VALUES('kitchen',1,'{}',1);");
  let actor = 2, jobs, pay, calls = [];
  const session = { currentUserId: () => actor, authenticatedUserId: () => actor };
  registerTestPrinting({ handle: (_, f) => { jobs = f; } }, () => true, db, session, a => { calls.push(a); return 'accepted'; }, true, true);
  registerPayments({ handle: (_, f) => { pay = f; } }, () => true, db, session, null);
  assert.equal(jobs({}, { action: 'configure', destination: 'bill-A', queue: 'A queue' }).ok, true);
  assert.equal(jobs({}, { action: 'configure', destination: 'bill-B', queue: 'B queue' }).ok, true);
  assert.equal(jobs({}, { action: 'configure', destination: 'kitchen', queue: 'Other' }).ok, false);
  assert.equal(jobs({}, { action: 'configureAlert', destination: 'kitchen', beep: true }).ok, false);
  assert.equal(jobs({}, { action: 'retryNotice', jobId: 1, requestId: 'notice', checked: true }).ok, false);
  assert.equal(jobs({}, { action: 'retry', jobId: 1, requestId: 'prep', checked: true }).ok, false);
  actor = 1;
  assert.equal(pay({}, { billId: 1, method: 'cash', account: 'B' }).ok, true);
  actor = 3;
  assert.equal(jobs({}, { action: 'configure', destination: 'bill-B', queue: 'Denied' }).ok, false);
  assert.equal(jobs({}, { action: 'list' }).data.jobs.length, 0);
  actor = 2;
  const list = jobs({}, { action: 'list' }).data;
  assert.deepEqual(list.queues.map(q => q.destination), ['bill-A', 'bill-B']);
  assert.deepEqual(list.notices, []);
  assert.equal(list.jobs.length, 1);
  assert.equal(list.jobs[0].result, 'unattempted');
  assert.equal(jobs({}, { action: 'retry', jobId: list.jobs[0].id, requestId: 'unchecked', checked: false }).ok, false);
  assert.equal(jobs({}, { action: 'retry', jobId: list.jobs[0].id, requestId: 'checked', checked: true }).ok, true);
  await new Promise(setImmediate);
  assert.equal(calls.length, 1);
  assert.equal(calls[0].queue, 'B queue');
});
