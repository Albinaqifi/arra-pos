const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs'), os = require('node:os'), path = require('node:path'), vm = require('node:vm');
const { openDatabase } = require('../src/desktop/database');
const { registerBusinessDays } = require('../src/desktop/business-days');
const { registerPayments } = require('../src/desktop/payments');
const { moduleSource } = require('./support/renderer-bundle');

test('real scoped service and renderer reconcile a lost handover after the day closes', async t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'arra-s089-renderer-'));
  const db = openDatabase(dir), realNow = Date.now;
  t.after(() => { Date.now = realNow; db.close(); fs.rmSync(dir, { recursive:true, force:true }); });
  db.exec(`INSERT INTO local_users(id,username,salt,password_hash) VALUES
    (1,'combined',x'00',x'00'),(2,'waiter',x'00',x'00'),(3,'a',x'00',x'00'),(4,'b',x'00',x'00');
    INSERT INTO financial_scopes VALUES(1,'combined'),(2,'waiter'),(3,'A'),(4,'B');
    INSERT INTO user_permissions VALUES(1,'business_days.close'),(2,'orders.view'),(2,'orders.change'),(3,'employees.view'),(4,'employees.view');
    INSERT INTO dining_tables(id,area) VALUES(1,'sample'),(2,'sample');
    INSERT INTO orders(id,table_id,opened_at,status) VALUES(1,1,1,'open'),(2,2,1,'open'); INSERT INTO order_waiter_ownership SELECT id,2,2,1,'open' FROM orders WHERE id NOT IN (SELECT order_id FROM order_waiter_ownership);
    INSERT INTO bills(id,order_id,actor_id,generated_at,total,fingerprint) VALUES(1,1,1,1,100,'first'),(2,2,1,1,200,'second');`);
  let actor=1, loseClose=false; const handlers={};
  const session={currentUserId:()=>actor,authenticatedUserId:()=>actor};
  for (const register of [registerBusinessDays,registerPayments]) register({handle:(channel,fn)=>handlers[channel]=fn},()=>true,db,session);
  const service=(channel,req)=>handlers[channel]({},JSON.parse(JSON.stringify(req)));
  const as=(id,fn)=>{actor=id;try{return fn();}finally{actor=1;}};
  const api={businessDays:async req=>{const result=service('arra:business-days',req);if(req.action==='shiftClose' && loseClose) throw Error('response lost');return result;}};
  class Component { constructor(props){this.props=props;} setState(value){Object.assign(this.state,value);} }
  const context={React:{Component,Fragment:'fragment',createElement:(type,props,...children)=>({type,props:props || {},children})},window:{arra:api}};
  vm.runInNewContext(moduleSource(path.resolve('src/admin/ShiftClose.js'),'Feature'),context);
  const Screen=context.Feature.ShiftClose, tick=()=>new Promise(setImmediate);
  Date.now=()=>Date.parse('2026-11-18T09:00:00Z');
  assert.equal(as(2,()=>service('arra:payment',{billId:1,method:'cash',account:'B'})).ok,true);
  const dayId=service('arra:business-days',{action:'shiftList'}).data.dayId;
  assert.equal(as(2,()=>service('arra:business-days',{action:'shiftList'})).ok,false);
  assert.deepEqual(as(3,()=>service('arra:business-days',{action:'list'})).data.issues.orders,[{}]);
  const first=new Screen({language:'en'}); first.componentDidMount(); await tick();
  assert.equal(first.active().total,100); assert.equal(first.state.day.issues.orders.length,1);
  assert.equal(as(2,()=>service('arra:business-days',{action:'shiftClose',shiftId:first.active().id})).ok,false);
  await first.review(); assert.equal(first.state.confirm,true);
  Date.now=()=>Date.parse('2026-11-18T16:00:00Z'); loseClose=true; await first.close();
  assert.equal(first.state.unknownId,first.active().id); first.componentWillUnmount(); loseClose=false;
  Date.now=()=>Date.parse('2026-11-18T16:10:00Z');
  assert.equal(as(2,()=>service('arra:payment',{billId:2,method:'card',account:'A'})).ok,true);
  Date.now=()=>Date.parse('2026-11-19T00:00:00Z');
  assert.equal(service('arra:business-days',{action:'close',dayId}).ok,true);
  const a=as(3,()=>service('arra:business-days',{action:'shiftList'})).data.shifts;
  const b=as(4,()=>service('arra:business-days',{action:'shiftList'})).data.shifts;
  assert.deepEqual(a.map(s=>s.total),[200,0]); assert.deepEqual(b.map(s=>s.total),[0,100]);
  const other=new Screen({language:'en'}); actor=3; other.componentDidMount(); await tick();
  assert.equal(other.state.unknownId,null); other.componentWillUnmount(); actor=1;
  let done=0; const resumed=new Screen({language:'en',onDone:()=>done++}); resumed.componentDidMount(); await tick();
  assert.equal(resumed.state.unknownId,first.state.unknownId); await resumed.check();
  assert.equal(resumed.state.completed.id,first.state.unknownId);
  assert.equal(resumed.state.completed.total,100); assert.equal(resumed.state.completed.closedAt,Date.parse('2026-11-18T16:00:00Z'));
  assert.equal(resumed.state.unknownId,null);
  const findDone=node=>node && typeof node==='object' ? (node.type==='button' && node.children.includes('Done') ? node : (node.children || []).map(findDone).find(Boolean)) : null;
  findDone(resumed.render()).props.onClick(); assert.equal(done,1); resumed.componentWillUnmount();
  assert.equal(db.prepare('SELECT count(*) AS n FROM payment_shifts').get().n,2);
  assert.equal(db.prepare('SELECT count(*) AS n FROM shift_closes').get().n,2);
  await tick();
});
