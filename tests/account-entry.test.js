const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs'), os = require('node:os'), path = require('node:path');
const { randomBytes, randomInt } = require('node:crypto');
const { openDatabase } = require('../src/desktop/database');
const { bootstrap, registerSession } = require('../src/desktop/session');
const { registerEmployeeConfig } = require('../src/desktop/employee-config');
const { hasPermissions } = require('../src/desktop/permissions');
const secret = () => randomBytes(24).toString('hex');
const pin = n => '0' + String(randomInt(10 ** (n-1))).padStart(n-1, '0');
test('account entry, provisioning, PIN validation, switching and revocation', t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'arra-entry-')); const db = openDatabase(dir);
  t.after(() => { db.close(); fs.rmSync(dir, { recursive: true, force: true }); });
  const ownerPass = secret(), restaurantPass = secret(), staffPass = secret(), waiterPin = pin(4), managerPin = pin(6);
  bootstrap(db, 'combined', ownerPass);
  const handlers = {}, event = {}; const ipc = { handle: (n, f) => { handlers[n] = f; } };
  const session = registerSession(ipc, e => e === event, db); registerEmployeeConfig(ipc, e => e === event, db, session);
  const call = (name, req, sender = event) => handlers['arra:' + name](sender, req);
  assert.equal(call('sign-in', {username:'combined',password:ownerPass}, {}).ok, false);
  assert.equal(call('sign-in', {username:'combined',password:ownerPass}).admin, true);
  assert.equal(session.currentUserId(), 1); assert.equal(call('waiters', {}).ok, false);
  assert.equal(call('employee-config',{action:'createRestaurant',username:'restaurant',password:restaurantPass}).ok,true);
  assert.equal(call('employee-config',{action:'create',username:'waiter',password:staffPass,pin:waiterPin}).ok,true);
  assert.equal(call('employee-config',{action:'createTransfer',username:'transfer',pin:managerPin}).ok,true);
  const users = call('employee-config',{action:'list'}).data.users;
  const get = name => users.find(u => u.username === name).id;
  const staff = get('waiter'), transfer = get('transfer');
  assert.equal(call('employee-config',{action:'permissions',id:staff,permissions:['tables.view']}).ok,true);
  assert.equal(call('employee-config',{action:'permissions',id:get('restaurant'),permissions:['tables.view']}).ok,false);
  assert.equal(call('employee-config',{action:'credential',id:staff,password:null,pin:''}).ok,false);
  call('sign-out',{});
  assert.equal(call('sign-in',{username:'waiter',password:staffPass}).ok,false);
  assert.equal(call('sign-in',{username:'restaurant',password:restaurantPass}).admin,false);
  assert.deepEqual(call('waiters',{}).data.map(u => u.name).sort(), ['transfer','waiter']);
  for (const bad of ['', 'x', waiterPin.slice(1), waiterPin + '0']) assert.equal(call('select-waiter',{id:staff,pin:bad}).ok,false);
  assert.equal(call('select-waiter',{id:1,pin:waiterPin}).ok,false);
  assert.equal(call('select-waiter',{id:staff,pin:waiterPin}).ok,true); assert.equal(hasPermissions(db,session,'tables.view'),true);
  assert.equal(call('employee-config',{action:'list'}).ok,false);
  assert.equal(call('select-waiter',{id:transfer,pin:waiterPin}).ok,false);
  assert.equal(call('select-waiter',{id:transfer,pin:managerPin}).ok,true); assert.equal(hasPermissions(db,session,'tables.view'),false);
  call('clear-waiter',{}); assert.equal(session.currentUserId(),null);
  call('sign-out',{}); call('sign-in',{username:'combined',password:ownerPass});
  const next = pin(6); assert.equal(call('employee-config',{action:'credential',id:transfer,password:null,pin:next}).ok,true);
  assert.equal(call('employee-config',{action:'account',id:staff,username:'waiter',active:false}).ok,true);
  call('sign-out',{}); call('sign-in',{username:'restaurant',password:restaurantPass});
  assert.equal(call('select-waiter',{id:staff,pin:waiterPin}).ok,false);
  assert.equal(call('select-waiter',{id:transfer,pin:next}).ok,true);
});
