test('manual close is authorized, atomic, persistent and retains outstanding issues', t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'arra-day-')); let db = openDatabase(dir);
  t.after(() => { db.close(); fs.rmSync(dir, { recursive: true, force: true }); });
  db.exec(`INSERT INTO local_users(id,username,salt,password_hash) VALUES(1,'admin',x'00',x'00'),(2,'other',x'00',x'00');
    INSERT INTO user_permissions VALUES(1,'business_days.close'),(2,'business_days.close');
    INSERT INTO financial_scopes VALUES(1,'combined'),(2,'A');
    INSERT INTO dining_tables(id,area) VALUES(1,'sample');
    INSERT INTO orders(id,table_id,opened_at,status) VALUES(1,1,1,'open');
    INSERT INTO preparation_rounds(id,order_id,request_id,number,actor_id,sent_at) VALUES(1,1,'r',1,1,1);
    INSERT INTO preparation_tickets(id,round_id,destination,adapter) VALUES(1,1,'kitchen','simulated');
    INSERT INTO print_jobs(id,ticket_id,created_at) VALUES(1,1,1);
    INSERT INTO print_attempts(job_id,request_id,actor_id,occurred_at,result) VALUES(1,'p',1,1,'uncertain');`);
  let current=1, auth=1, handler;
  const session={currentUserId:()=>current,authenticatedUserId:()=>auth};
  const register=()=>registerBusinessDays({handle:(_,fn)=>handler=fn}, e=>e.allowed, db, session);
  register(); const call=req=>handler({allowed:true},req);
  const initial=call({action:'list'}); assert.equal(initial.ok,true); const id=initial.data.days[0].id;
  assert.equal(initial.data.issues.orders[0].id,1); assert.equal(initial.data.issues.printJobs[0].result,'uncertain');
  current=auth=2; assert.equal(call({action:'close',dayId:id}).ok,false);
  current=1; assert.equal(call({action:'close',dayId:id}).ok,false);
  current=auth=1; assert.equal(handler({allowed:false},{action:'close',dayId:id}).ok,false);
  assert.equal(call({action:'close',dayId:id,extra:1}).ok,false);
  db.exec("CREATE TRIGGER fail_close BEFORE INSERT ON application_audit WHEN NEW.entity_type='business_day' BEGIN SELECT RAISE(ABORT,'fail'); END");
  assert.equal(call({action:'close',dayId:id}).ok,false); assert.equal(db.prepare('SELECT closed_at FROM business_days WHERE id=?').get(id).closed_at,null);
  db.exec('DROP TRIGGER fail_close');
  const closed=call({action:'close',dayId:id}); assert.equal(closed.ok,true); assert.equal(closed.data.issues.orders.length,1); assert.equal(closed.data.issues.printJobs.length,1);
  assert.equal(call({action:'close',dayId:id}).ok,false); assert.equal(db.prepare('SELECT count(*) AS n FROM business_days').get().n,2);
  assert.equal(db.prepare('SELECT status FROM orders WHERE id=1').get().status,'open');
  assert.throws(()=>db.prepare('UPDATE business_days SET closed_at=1 WHERE id=?').run(id));
  db.close(); db=openDatabase(dir); register();
  const saved=call({action:'list'}).data.days.find(x=>x.id===id); assert.equal(saved.closedBy,1); assert.equal(saved.closedAt,closed.data.closedAt); assert.equal(saved.issues.printJobs[0].result,'uncertain');
});

