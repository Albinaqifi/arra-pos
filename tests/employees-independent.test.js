const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { openDatabase } = require('../src/desktop/database');
const { bootstrap, createSession } = require('../src/desktop/session');
const { registerEmployeeConfig } = require('../src/desktop/employee-config');
const { registerMenuConfig } = require('../src/desktop/menu-config');
const { registerTableConfig } = require('../src/desktop/table-config');
const { randomBytes, randomInt } = require('node:crypto');
const samplePin = () => String(randomInt(10000)).padStart(4,'0');

test('account changes revoke access, survive reopen, and prevent identity switching for configuration', t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'arra-employee-independent-'));
  let db = openDatabase(dir);
  t.after(() => { db.close(); fs.rmSync(dir, { recursive: true, force: true }); });
  bootstrap(db, 'manager', 'manager sample password');
  const session = createSession(db), handlers = {}, trusted = {};
  const ipc = { handle: (channel, fn) => { handlers[channel] = fn; } };
  for (const register of [registerEmployeeConfig, registerMenuConfig, registerTableConfig]) register(ipc, e => e === trusted, db, session);
  const call = (channel, req) => handlers['arra:' + channel](trusted, req);
  const password = randomBytes(24).toString('hex'), pin = samplePin();
  assert.equal(session.signIn({ username: 'manager', password: 'manager sample password' }).ok, true);
  assert.equal(call('employee-config', { action: 'createRestaurant', username: 'restaurant', password }).ok, true);
  assert.equal(call('employee-config', { action: 'create', username: 'worker', password: 'worker sample password', pin }).ok, true);
  const id = db.prepare('SELECT id FROM local_users WHERE username = ?').get('worker').id;
  assert.equal(call('employee-config', { action: 'permissions', id, permissions: ['tables.view'] }).ok, true);
  session.signOut();
  assert.equal(session.signIn({ username: 'worker', password: 'worker sample password' }).ok, false);
  assert.equal(session.signIn({ username: 'restaurant', password }).ok, true);
  assert.equal(session.selectWaiter({ id: 1, pin }).ok, false);
  assert.equal(session.selectWaiter({ id, pin }).ok, true);
  assert.equal(call('table-config', { action: 'area', id: null, name: 'Unexpected', active: true }).ok, false);
  assert.equal(call('menu-config', { action: 'list' }).ok, false);
  assert.equal(call('employee-config', { action: 'permissions', id, permissions: ['employees.change'] }).ok, false);
  session.signOut();
  session.signIn({ username: 'manager', password: 'manager sample password' });
  assert.equal(call('employee-config', { action: 'account', id, username: 'worker', active: false }).ok, true);
  session.signOut();
  assert.equal(session.signIn({ username: 'worker', password: 'worker sample password' }).ok, false);
  assert.equal(session.signIn({ username: 'restaurant', password }).ok, true);
  assert.equal(session.selectWaiter({ id, pin }).ok, false);
  db.close(); db = openDatabase(dir);
  assert.equal(db.prepare('SELECT active FROM local_users WHERE id = ?').get(id).active, 0);
  const change = db.prepare('SELECT actor_id, target_id, old_active, new_active FROM employee_account_audit').get();
  assert.deepEqual([change.actor_id, change.target_id, change.old_active, change.new_active], [1, id, 1, 0]);
  assert.throws(() => db.exec('DELETE FROM employee_account_audit'));
  assert.equal(db.prepare('SELECT count(*) AS n FROM employee_permission_audit WHERE actor_id = 1 AND target_id = ? AND permission = ? AND granted = 1').get(id, 'tables.view').n, 1);
  assert.equal(db.prepare('SELECT count(*) AS n FROM dining_areas WHERE name = ?').get('Unexpected').n, 0);
});

test('grant revocation affects an active session and audit excludes credentials', t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'arra-employee-revoke-'));
  const db = openDatabase(dir);
  t.after(() => { db.close(); fs.rmSync(dir, { recursive: true, force: true }); });
  bootstrap(db, 'manager', 'manager sample password');
  const manager = createSession(db), worker = createSession(db), handlers = {}, trusted = {};
  const ipc = { handle: (channel, fn) => { handlers[channel] = fn; } };
  registerEmployeeConfig(ipc, e => e === trusted, db, manager);
  manager.signIn({ username: 'manager', password: 'manager sample password' });
  const call = req => handlers['arra:employee-config'](trusted, req);
  const password = randomBytes(24).toString('hex'), pin = samplePin(), replacement = samplePin();
  assert.equal(call({ action: 'createRestaurant', username: 'restaurant', password }).ok, true);
  assert.equal(call({ action: 'create', username: 'worker', password: 'worker sample password', pin }).ok, true);
  const id = db.prepare('SELECT id FROM local_users WHERE username = ?').get('worker').id;
  assert.equal(call({ action: 'permissions', id, permissions: ['tables.view'] }).ok, true);
  worker.signIn({ username: 'restaurant', password }); worker.selectWaiter({ id, pin });
  const { hasPermissions } = require('../src/desktop/permissions');
  assert.equal(hasPermissions(db, worker, 'tables.view'), true);
  assert.equal(call({ action: 'permissions', id, permissions: [] }).ok, true);
  assert.equal(hasPermissions(db, worker, 'tables.view'), false);
  assert.equal(call({ action: 'credential', id, password: 'new sample password', pin: replacement }).ok, true);
  const exposed = JSON.stringify(call({ action: 'list' }).data);
  for (const secret of ['worker sample password', 'new sample password', pin, replacement]) assert.equal(exposed.includes(secret), false);
  const events = db.prepare('SELECT actor_id, target_id, granted FROM employee_permission_audit ORDER BY id').all();
  assert.deepEqual(events.map(x => [x.actor_id, x.target_id, x.granted]), [[1, id, 1], [1, id, 0]]);
});
