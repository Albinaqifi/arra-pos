const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { openDatabase } = require('../src/desktop/database');
const { bootstrap, createSession } = require('../src/desktop/session');
const { hasPermissions } = require('../src/desktop/permissions');
const { registerEmployeeConfig } = require('../src/desktop/employee-config');
const { randomBytes, randomInt } = require('node:crypto');

test('employee changes require authenticated administrator, protect credentials and retain transactional audit', t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'arra-employees-')); let db = openDatabase(dir);
  t.after(() => { db.close(); fs.rmSync(dir, { recursive: true, force: true }); });
  bootstrap(db, 'admin', 'sample admin password');
  db.prepare("UPDATE financial_scopes SET scope='combined' WHERE user_id=1").run();
  const session = createSession(db), handlers = {}, trusted = {};
  registerEmployeeConfig({ handle: (channel, fn) => handlers[channel] = fn }, e => e === trusted, db, session);
  const invoke = req => handlers['arra:employee-config'](trusted, req);
  const restaurantPassword=randomBytes(24).toString('hex'), pin=String(randomInt(10000)).padStart(4,'0'), nextPin=String(randomInt(10000)).padStart(4,'0');
  assert.equal(invoke({ action: 'list' }).ok, false);
  assert.equal(session.signIn({ username: 'admin', password: 'sample admin password' }).ok, true);
  assert.equal(invoke({ action: 'createRestaurant', username: 'restaurant', password: restaurantPassword }).ok, true);
  assert.equal(handlers['arra:employee-config']({}, { action: 'list' }).ok, false);
  assert.equal(invoke({ action: 'create', username: 'staff', password: 'sample staff password', pin }).ok, true);
  const user = db.prepare('SELECT id, salt, password_hash, pin_salt, pin_hash FROM local_users WHERE username = ?').get('staff');
  assert.notDeepEqual(Buffer.from(user.password_hash), Buffer.from('sample staff password')); assert.notDeepEqual(Buffer.from(user.pin_hash), Buffer.from(pin));
  assert.equal(invoke({ action: 'permissions', id: user.id, permissions: ['orders.view', 'financial.A'] }).ok, false);
  assert.equal(invoke({ action: 'permissions', id: 1, permissions: ['employees.change'] }).ok, false);
  assert.equal(invoke({ action: 'permissions', id: user.id, permissions: ['orders.view', 'employees.view', 'employees.change'] }).ok, true);
  assert.equal(db.prepare('SELECT count(*) AS n FROM employee_permission_audit WHERE actor_id = 1 AND target_id = ?').get(user.id).n, 3);
  assert.equal(invoke({ action: 'permissions', id: user.id, permissions: ['orders.view', 'employees.view', 'employees.change'] }).ok, true);
  assert.equal(db.prepare('SELECT count(*) AS n FROM employee_permission_audit').get().n, 3);
  db.exec("CREATE TRIGGER fail_audit BEFORE INSERT ON employee_permission_audit BEGIN SELECT RAISE(ABORT, 'failure'); END");
  assert.equal(invoke({ action: 'permissions', id: user.id, permissions: ['employees.view', 'employees.change'] }).ok, false);
  assert.equal(db.prepare("SELECT count(*) AS n FROM user_permissions WHERE user_id = ? AND permission = 'orders.view'").get(user.id).n, 1);
  db.exec('DROP TRIGGER fail_audit');
  assert.throws(() => db.exec('DELETE FROM employee_permission_audit'));
  assert.equal(session.signOut().ok, true);
  assert.equal(session.signIn({ username: 'staff', password: 'sample staff password' }).ok, false);
  assert.equal(session.signIn({ username: 'restaurant', password: restaurantPassword }).ok, true);
  assert.equal(session.selectWaiter({ id: 1, pin }).ok, false);
  assert.equal(invoke({ action: 'list' }).ok, false);
  assert.equal(hasPermissions(db, session, 'tables.change'), false);
  assert.equal(hasPermissions(db, session, 'menu.change'), false);
  assert.equal(session.selectWaiter({ id: user.id, pin }).ok, true);
  assert.equal(invoke({ action: 'credential', id: 1, password: 'replacement', pin: null }).ok, false);
  assert.equal(invoke({ action: 'permissions', id: user.id, permissions: ['orders.view', 'employees.view', 'employees.change', 'menu.change'] }).ok, false);
  session.signOut(); session.signIn({ username: 'admin', password: 'sample admin password' });
  db.exec("CREATE TRIGGER fail_account_audit BEFORE INSERT ON employee_account_audit BEGIN SELECT RAISE(ABORT, 'failure'); END");
  assert.equal(invoke({ action: 'account', id: user.id, username: 'renamed', active: true }).ok, false);
  assert.equal(db.prepare('SELECT username FROM local_users WHERE id = ?').get(user.id).username, 'staff');
  db.exec('DROP TRIGGER fail_account_audit');
  assert.equal(invoke({ action: 'account', id: user.id, username: 'renamed', active: true }).ok, true);
  assert.deepEqual({ ...db.prepare('SELECT actor_id, target_id, old_username, new_username FROM employee_account_audit').get() }, { actor_id: 1, target_id: user.id, old_username: 'staff', new_username: 'renamed' });
  assert.throws(() => db.exec('DELETE FROM employee_account_audit'));
  db.exec("CREATE TRIGGER fail_credential_audit BEFORE INSERT ON employee_credential_audit BEGIN SELECT RAISE(ABORT, 'failure'); END");
  assert.equal(invoke({ action: 'credential', id: user.id, password: 'replacement', pin: nextPin }).ok, false);
  db.exec('DROP TRIGGER fail_credential_audit');
  assert.equal(invoke({ action: 'credential', id: user.id, password: 'replacement', pin: nextPin }).ok, true);
  assert.deepEqual({ ...db.prepare('SELECT actor_id, target_id, password_changed, pin_changed FROM employee_credential_audit').get() }, { actor_id: 1, target_id: user.id, password_changed: 1, pin_changed: 1 });
  assert.throws(() => db.exec('DELETE FROM employee_credential_audit'));
  session.signOut(); assert.equal(session.signIn({ username: 'renamed', password: 'sample staff password' }).ok, false);
  assert.equal(session.signIn({ username: 'renamed', password: 'replacement' }).ok, false);
  assert.equal(session.signIn({ username: 'restaurant', password: restaurantPassword }).ok, true);
  assert.equal(session.selectWaiter({ id: user.id, pin: nextPin }).ok, true);
  db.prepare('UPDATE local_users SET active = 0 WHERE id = ?').run(user.id);
  assert.equal(session.currentUserId(), null); assert.equal(invoke({ action: 'list' }).ok, false);
});
